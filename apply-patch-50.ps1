   * ---------------------------------------------------------------
   * Validate payment date
   * ---------------------------------------------------------------
   */

  const paymentDate =
    new Date(date);

  if (
    Number.isNaN(
      paymentDate.getTime()
    )
  ) {
    return NextResponse.json(
      {
        error:
          "Invalid payment date",
      },
      {
        status: 400,
      }
    );
