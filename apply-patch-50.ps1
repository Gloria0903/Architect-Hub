            Math.max(
              currentBudget -
                currentPaid,
              0
            );

          /*
           * -----------------------------------------------------
           * Prevent overpayment
           * -----------------------------------------------------
           */

          if (
            amount >
            currentOutstanding
          ) {
            throw new Error(
              `PAYMENT_EXCEEDS_BALANCE:${currentOutstanding}`
            );
          }

          /*
           * -----------------------------------------------------
           * Create payment record
           * -----------------------------------------------------
           */

          const payment =
            await tx.payment.create({
              data: {
                projectId,

                recordedById:
                  session.user.id,

                amount,

                date: paymentDate,

                reference:
                  reference?.trim() ||
                  null,

                note:
                  note?.trim() ||
                  null,
              },

              select: {
                id: true,

                amount: true,

                date: true,

                reference: true,

                note: true,

                createdAt: true,

                projectId: true,

                recordedById: true,
              },
            });

          /*
           * -----------------------------------------------------
           * Update project paid amount
           * -----------------------------------------------------
           *
           * Payment increases PAID.
           *
           * Payment does NOT increase INVOICED.
           */

          const updatedProject =
            await tx.project.update({
