            currentProject.archivedAt
          ) {
            throw new Error(
              "PROJECT_ARCHIVED"
            );
          }

          /*
           * -----------------------------------------------------
           * Recalculate from latest state
           * -----------------------------------------------------
           */

          const currentBudget =
            Number(
