   * ---------------------------------------------------------------
   * Financial validation
   * ---------------------------------------------------------------
   *
   * Correct relationship:
   *
   *     Budget >= Invoiced >= Paid
   *
   * Therefore:
   *
   *     Outstanding = Budget - Paid
   *
   * (Invoiced is tracked separately via /api/invoices for reference,
   * but no longer constrains what payments are allowed.)
