     * ---------------------------------------------------------------
     * Unexpected server error
     * ---------------------------------------------------------------
     */

    console.error(
      "Payment creation error:",
      error
    );

    return NextResponse.json(
      {
        error:
          "Failed to record payment",
      },
      {
        status: 500,
      }
    );
  }
