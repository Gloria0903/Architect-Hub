   * ---------------------------------------------------------------
   * Archived project protection
   * ---------------------------------------------------------------
   */

  if (project.archivedAt) {
    return NextResponse.json(
      {
        error:
          "Payments cannot be recorded for archived projects",
      },
      {
        status: 400,
      }
    );
