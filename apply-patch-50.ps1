   * ---------------------------------------------------------------
   * Prevent overpayment
   * ---------------------------------------------------------------
   */

  if (
    amount >
    outstandingBalance
  ) {
    return NextResponse.json(
      {
        error:
          `Payment exceeds the remaining contract balance of ${outstandingBalance}`,
      },
      {
        status: 400,
      }
