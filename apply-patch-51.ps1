                id: true,
                name: true,
                sheetNo: true,
                location: true,
                description: true,
                status: true,
                priority: true,
                startDate: true,
                dueDate: true,
                completionDate: true,
                clientId: true,
                architectId: true,
                supervisorId: true,
                createdAt: true,
                updatedAt: true,
              },
            });

          /*
           * Record assignment history.
           */
          await tx.assignmentRecord.create({
            data: {
              projectId: id,

              fromArchitectId:
                project.architectId,

              toArchitectId:
                toArchitectId,

              reason:
                reason || null,

              performedById:
                session.user.id,
            },
          });

          return updated;
        }
      );
  } catch (error) {
    console.error(
      "Project reassignment failed:",
      error
    );

    return NextResponse.json(
      {
        error:
          "Failed to reassign project. Please try again.",
      },
      {
        status: 500,
      }
    );
  }

  /*
   * ---------------------------------------------------------
   * Notify new architect
   * ---------------------------------------------------------
   *
   * Notification failure must not undo the successful
   * reassignment.
   */

  try {
    await notifyProjectAssignment({
      userId: toArchitectId,

      projectId: id,

      projectName:
        `${project.name} (${project.sheetNo})`,

      assignedRole: "ARCHITECT",

      assignedByName:
        session.user.name ??
        "An administrator",
    });
  } catch (error) {
    console.error(
      "Project reassignment notification failed:",
      error
    );
  }

  /*
   * Same flat-fetch pattern used elsewhere in this app: matches what
   * the removed nested client/architect/supervisor select used to
   * provide, without the join that fails on this host.
   */
  const [reassignClient, reassignArchitect, reassignSupervisor] = await Promise.all([
    prisma.client.findUnique({
      where: { id: updatedProject.clientId },
      select: {
        id: true,
        name: true,
        contactPerson: true,
        email: true,
        phone: true,
        address: true,
        portalEnabled: true,
      },
    }),
    updatedProject.architectId
      ? prisma.user.findUnique({
          where: { id: updatedProject.architectId },
          select: { id: true, name: true, initials: true, avatarUrl: true },
        })
      : Promise.resolve(null),
    updatedProject.supervisorId
      ? prisma.user.findUnique({
          where: { id: updatedProject.supervisorId },
          select: { id: true, name: true, initials: true, avatarUrl: true },
        })
      : Promise.resolve(null),
  ]);

  /*
   * ---------------------------------------------------------
   * Return safe response
   * ---------------------------------------------------------
   */

  return NextResponse.json({
    success: true,

    message:
      "Project reassigned successfully",

    project: {
      ...updatedProject,
      client: reassignClient,
      architect: reassignArchitect,
      supervisor: reassignSupervisor,
    },
  });
}
