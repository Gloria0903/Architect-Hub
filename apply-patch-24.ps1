          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();

      return created;
    },
    [refresh]
  );

  // ─── Comments ─────────────────────────────────────────────────────────────

  const addComment = useCallback(
    async (
      data: Parameters<
        AppActions["addComment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/comments",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            type:
              data.type.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const resolveComment = useCallback(
