        formData.append(
          "projectId",
          projectId
        );

        formData.append(
          "category",
          category
        );

        let response: Response;

        try {
          response = await fetch(
            "/api/documents",
            {
              method: "POST",
              body: formData,
              credentials:
                "same-origin",
              cache: "no-store",
