export async function DELETE(
  _: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const session = await auth();

  if (!session) {
    return NextResponse.json(
      { error: "Unauthorized" },
      { status: 401 }
    );
  }

  /*
   * Client deletion is ADMIN ONLY.
   */
  if (!isAdmin(session)) {
    return NextResponse.json(
      { error: "Forbidden" },
      { status: 403 }
    );
  }

  const { id } = await params;

  if (!id) {
    return NextResponse.json(
      { error: "Client ID is required." },
      { status: 400 }
    );
  }

  try {
    /*
     * Do not allow deletion while projects still belong
     * to this client.
     */
    const projectCount = await prisma.project.count({
      where: {
        clientId: id,
      },
    });

    if (projectCount > 0) {
      return NextResponse.json(
        {
          error:
            "Cannot delete a client with existing projects. Delete or reassign their projects first.",
        },
        { status: 409 }
      );
    }

    /*
     * Also block deletion if there are comment/communication records
     * tied to this client -- ClientComment.clientId doesn't cascade on
     * delete (correctly: those records should outlive the client if
     * the client's projects are still around), so a raw delete would
     * otherwise fail with a generic error instead of this clear one.
     */
    const commentCount = await prisma.clientComment.count({
      where: { clientId: id },
    });

    if (commentCount > 0) {
      return NextResponse.json(
        {
          error:
            "Cannot delete a client with existing communication records. Those need to be cleared first.",
        },
        { status: 409 }
      );
    }

    /*
     * Verify the client exists before deletion.
     */
    const client = await prisma.client.findUnique({
      where: { id },
      select: { id: true },
    });

    if (!client) {
      return NextResponse.json(
        { error: "Client not found." },
        { status: 404 }
      );
    }

    await prisma.client.delete({
      where: { id },
    });

    return NextResponse.json({
      success: true,
    });
  } catch (error) {
    console.error(
      `Failed to delete client ${id}:`,
      error
    );

    /*
     * Safety net matching the one added to staff deletion: the checks
     * above enumerate the relations we know about (projects, comments),
     * but a foreign-key violation on any other table this schema might
     * reference from Client means the same underlying situation --
     * existing records elsewhere depending on this client. Give the
     * same clear answer rather than a generic failure.
     */
    if (
      error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "P2003"
    ) {
      return NextResponse.json(
        {
          error:
            "This client has existing records elsewhere in the system and can't be deleted yet. Remove the related records first.",
        },
        { status: 409 }
      );
    }

    return NextResponse.json(
      {
        error:
          "Failed to delete client. Please try again.",
      },
      { status: 500 }
    );
  }
}
