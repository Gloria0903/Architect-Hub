import bcrypt from "bcryptjs";
import { validatePassword, generateTemporaryPassword } from "@/lib/password-policy";

export async function PATCH(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const session = await auth();
  if (!session) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  const { id } = await params;
  const isSelf = id === session.user.id;
  const isAdmin = session.user.role === "ADMIN";

  if (!isAdmin && !isSelf) {
    return NextResponse.json({ error: "Forbidden" }, { status: 403 });
  }

  const body = await req.json();

  // Only admins can change role, email, department, or active status.
  if (!isAdmin && (body.role || body.email || body.department !== undefined || body.isActive !== undefined)) {
    return NextResponse.json({ error: "Only an admin can change role, email, department, or active status" }, { status: 403 });
  }

  // Prevent an admin from locking themselves out entirely.
  if (isAdmin && isSelf && body.isActive === false) {
    return NextResponse.json({ error: "You cannot deactivate your own account" }, { status: 400 });
  }

  const initials = body.name
    ? body.name.split(" ").map((w: string) => w[0]).join("").slice(0, 2).toUpperCase()
    : undefined;

  let hashedPassword: string | undefined;
  let generatedPassword: string | undefined;
  let mustResetPassword: boolean | undefined;

  if (body.password) {
    if (isSelf && !isAdmin) {
      // Self-service password change must prove the current password first.
      const existing = await prisma.user.findUnique({ where: { id } });
      if (!existing) return NextResponse.json({ error: "Not found" }, { status: 404 });
      if (!body.currentPassword || !(await bcrypt.compare(body.currentPassword, existing.password))) {
        return NextResponse.json({ error: "Current password is incorrect" }, { status: 400 });
      }
    }
    const check = validatePassword(body.password);
    if (!check.valid) return NextResponse.json({ error: check.errors.join(" ") }, { status: 400 });
    hashedPassword = await bcrypt.hash(body.password, 12);
    mustResetPassword = false;
  } else if (isAdmin && body.resetPassword === true) {
    // Admin-triggered reset: generate a fresh temp password, force change on next login.
    generatedPassword = generateTemporaryPassword();
    hashedPassword = await bcrypt.hash(generatedPassword, 12);
    mustResetPassword = true;
  }

  const user = await prisma.user.update({
    where: { id },
    data: {
      ...(body.name && { name: body.name, initials }),
      ...(isAdmin && body.email && { email: body.email }),
      ...(isAdmin && body.role && { role: body.role }),
      ...(body.phone !== undefined && { phone: body.phone }),
      ...(isAdmin && body.department !== undefined && { department: body.department }),
      ...(isAdmin && body.isActive !== undefined && { isActive: body.isActive }),
      ...(hashedPassword && { password: hashedPassword, passwordChangedAt: new Date() }),
      ...(mustResetPassword !== undefined && { mustResetPassword }),
      ...(hashedPassword && { failedLoginAttempts: 0, lockedUntil: null }),
    },
    select: {
      id: true, name: true, email: true, role: true, phone: true, department: true,
      initials: true, avatarUrl: true, isActive: true, mustResetPassword: true,
    },
  });

  return NextResponse.json({ ...user, temporaryPassword: generatedPassword });
}

export async function DELETE(_: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const session = await auth();
  if (!session) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  if (session.user.role !== "ADMIN") return NextResponse.json({ error: "Forbidden" }, { status: 403 });

  const { id } = await params;
  if (id === session.user.id) return NextResponse.json({ error: "Cannot delete yourself" }, { status: 400 });

  const existing = await prisma.user.findUnique({ where: { id }, select: { id: true, name: true } });
  if (!existing) {
    return NextResponse.json({ error: "Staff member not found" }, { status: 404 });
  }

  /*
   * A staff account almost always has real work attached to it --
   * assigned projects, daily logs they submitted, documents they
   * uploaded, payments/invoices they recorded -- none of which cascade
   * on user deletion (correctly: deleting a person shouldn't delete
   * the firm's project history or financial records). Attempting a
   * raw delete against any of that throws an unhandled foreign-key
   * violation, which is why this previously just silently failed.
   * Check first and give a clear, actionable answer instead.
   */
  const [
    assignedProjects,
    supervisedProjects,
    dailyLogs,
    documents,
    payments,
    invoices,
    assignmentRecords,
    taskAssignments,
    milestonesCreated,
    snapshotsCreated,
    archiveHistory,
  ] =
    await Promise.all([
      prisma.project.count({ where: { architectId: id } }),
      prisma.project.count({ where: { supervisorId: id } }),
      prisma.dailyLog.count({ where: { authorId: id } }),
      prisma.document.count({ where: { uploadedById: id } }),
      prisma.payment.count({ where: { recordedById: id } }),
      prisma.invoice.count({ where: { recordedById: id } }),
      prisma.assignmentRecord.count({
        where: {
          OR: [
            { fromArchitectId: id },
            { toArchitectId: id },
            { performedById: id },
          ],
        },
      }),
      prisma.projectTask.count({ where: { assigneeId: id } }),
      prisma.projectMilestone.count({ where: { createdById: id } }),
      prisma.progressSnapshot.count({ where: { createdById: id } }),
      prisma.project.count({
        where: {
          OR: [{ archivedById: id }, { restoredById: id }],
        },
      }),
    ]);

  const hasHistory =
    assignedProjects > 0 ||
    supervisedProjects > 0 ||
    dailyLogs > 0 ||
    documents > 0 ||
    payments > 0 ||
    invoices > 0 ||
    assignmentRecords > 0 ||
    taskAssignments > 0 ||
    milestonesCreated > 0 ||
    snapshotsCreated > 0 ||
    archiveHistory > 0;

  if (hasHistory) {
    return NextResponse.json(
      {
        error: `${existing.name} has existing work on record (projects, daily logs, documents, payments, or invoices) and can't be permanently deleted -- that history needs to stay intact. Deactivate their account instead to block their login while keeping the firm's records complete.`,
      },
      { status: 409 }
    );
  }

  try {
    await prisma.user.delete({ where: { id } });
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error(`Failed to delete staff member ${id}:`, error);

    /*
     * Safety net: the pre-check above enumerates the relations we know
     * about, but this schema has enough User-referencing tables (audit
     * trails, login history, etc.) that a manual list can miss one --
     * it already has once. Any foreign-key violation (Prisma code
     * P2003) at this point means the same underlying situation as the
     * pre-check catches, just via a table we didn't explicitly count.
     * Give the same clear, actionable answer either way instead of a
     * generic failure message.
     */
    if (
      error &&
      typeof error === "object" &&
      "code" in error &&
      error.code === "P2003"
    ) {
      return NextResponse.json(
        {
          error: `${existing.name} has existing records elsewhere in the system and can't be permanently deleted -- that history needs to stay intact. Deactivate their account instead to block their login while keeping the firm's records complete.`,
        },
        { status: 409 }
      );
    }

    return NextResponse.json({ error: "Failed to delete staff member" }, { status: 500 });
  }
}

