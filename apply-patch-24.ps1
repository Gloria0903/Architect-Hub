          );
        } catch (error) {
          console.error(
            "Document upload network error:",
            error
          );

          throw new Error(
            "Could not connect to the document upload service."
          );
        }

        const contentType =
          response.headers.get(
            "content-type"
          ) || "";

        let result: unknown = null;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          result = await response
            .json()
            .catch(() => null);
        } else {
          const text =
            await response
              .text()
              .catch(() => "");

          result = {
            error:
              text ||
              `Upload failed with HTTP ${response.status}`,
          };
        }

        console.log(
          "Document upload response:",
          {
            status: response.status,
            result,
          }
        );

        if (!response.ok) {
          if (
            response.status === 401
          ) {
            throw new Error(
              "Your session has expired. Please log in again."
            );
          }

          if (
            response.status === 403
          ) {
            throw new Error(
              "You do not have permission to upload documents to this project."
            );
          }

          if (
            response.status === 413
          ) {
            throw new Error(
              "The file is too large to upload."
            );
          }

          let message =
            `Upload failed with HTTP ${response.status}`;

          if (
            typeof result ===
              "object" &&
            result !== null
          ) {
            const body =
              result as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }

          throw new Error(message);
        }

        if (
          typeof result !==
            "object" ||
          result === null ||
          !("id" in result)
        ) {
          console.error(
            "Upload response did not contain a document ID:",
            result
          );

          throw new Error(
            "The server accepted the upload but did not return a document record."
          );
        }

        console.log(
          "Document uploaded successfully:",
          result
        );

        await refresh();
      },
      [refresh]
    );

