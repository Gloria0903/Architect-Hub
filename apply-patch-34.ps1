    // step specifically on resource-constrained shared hosting (cPanel/
    // CloudLinux CageFS, like HostPinnacle) -- Next.js spawns many
    // parallel worker threads by default to speed up builds, which
    // exceeds the process/thread limit CageFS enforces per account.
    // Forces a single-threaded build instead. Applied everywhere, not
    // just conditionally for that host -- costs a little build time on
    // platforms with ample resources (Vercel/Railway), in exchange for
    // one fewer thing that can silently differ between environments.
    workerThreads: false,
    cpus: 1,
  },
