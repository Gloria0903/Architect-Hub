// ─── Provider ────────────────────────────────────────────────────────────────

export function AppProvider({
  children,
}: {
  children: ReactNode;
}) {
  const {
    status,
    data: session,
  } = useSession();

  const isStaffSession =
    status === "authenticated" &&
    session?.user?.role !== "CLIENT";

  const [state, setState] =
    useState<AppState>({
      staff: [],
      clients: [],
      projects: [],
      logs: [],
      comments: [],
      payments: [],
      notifications: [],
      documents: [],
      loading: false,
      error: null,
    });

  /*
   * Prevent multiple refresh calls from executing
   * simultaneously. If a call comes in while one is already
   * running, we don't just hand back the in-flight promise as-is —
   * that promise may have been *started* before this caller's own
   * mutation (e.g. an avatar or document upload) finished writing to
   * the server, so its snapshot would be stale by the time it
   * resolves. Instead we mark `refreshQueued` and guarantee a fresh
   * follow-up run starts the moment the current one finishes, so
   * every caller is guaranteed data fetched *after* their own write.
   */
  const refreshInFlight =
    useRef<Promise<void> | null>(null);
  const refreshQueued = useRef(false);

  // ─── Refresh all staff data ───────────────────────────────────────────────

  const refresh = useCallback(async (): Promise<void> => {
    if (!isStaffSession) {
      return;
    }

    if (refreshInFlight.current) {
      refreshQueued.current = true;
      return refreshInFlight.current;
    }

    const runOnce = (): Promise<void> => (async () => {
      try {
        setState((s) => ({
          ...s,
          loading: true,
          error: null,
        }));

        /*
         * Each request is deliberately kept separate inside Promise.all.
         * If one endpoint returns HTTP 500, the improved apiFetch()
         * will now tell us EXACTLY which endpoint failed.
         */
        const [
          staff,
          clients,
          projects,
          logs,
          comments,
          payments,
          notificationResponse,
          documents,
        ] = await Promise.all([
          apiFetch<StaffMember[]>(
            "/api/staff"
          ),

          apiFetch<Client[]>(
            "/api/clients"
          ),

          apiFetch<Project[]>(
            "/api/projects"
          ),

          apiFetch<DailyLog[]>(
            "/api/logs"
          ),

          apiFetch<ClientComment[]>(
            "/api/comments"
          ),

          apiFetch<Payment[]>(
            "/api/payments"
          ),

          apiFetch<{
            notifications: Notification[];
            unreadCount: number;
          }>(
            "/api/notifications"
          ),

          apiFetch<Document[]>(
            "/api/documents"
          ),
        ]);

        const notifications =
          notificationResponse?.notifications ??
          [];

        setState({
          staff: staff ?? [],
          clients: clients ?? [],
          projects: projects ?? [],
          logs: logs ?? [],
          comments: comments ?? [],
          payments: payments ?? [],
          notifications,
          documents: documents ?? [],
          loading: false,
          error: null,
        });
      } catch (error) {
        console.error(
          "Failed to refresh application data:",
          error
        );

        const message =
          error instanceof Error
            ? error.message
            : "Failed to load application data.";

        setState((s) => ({
          ...s,
          loading: false,
          error: message,
        }));
      }
    })();

    const promise = runOnce().then(() => {
      // If another caller asked for a refresh while this run was in
      // flight, their write may have landed after our fetch started —
      // run once more immediately so they get a fresh snapshot instead
      // of silently keeping whatever we just fetched.
      if (refreshQueued.current) {
        refreshQueued.current = false;
        refreshInFlight.current = runOnce().finally(() => {
          refreshInFlight.current = null;
        });
        return refreshInFlight.current;
      }
      refreshInFlight.current = null;
    });

    refreshInFlight.current = promise;

    return promise;
  }, [isStaffSession]);

  // ─── Initial data load ────────────────────────────────────────────────────

  useEffect(() => {
  if (status === "loading") {
    return;
  }

  if (isStaffSession) {
    void refresh();
  }
}, [status, isStaffSession, refresh]);

  // ─── Keep data fresh ──────────────────────────────────────────────────────

  useEffect(() => {
    if (!isStaffSession) {
      return;
    }

    const refreshIfVisible = () => {
      if (
        document.visibilityState ===
          "visible" &&
        !isFilePickerCooldownActive()
      ) {
        void refresh();
      }
    };

    const interval = setInterval(
      refreshIfVisible,
      30000
    );

    const onFocus = () => {
      // Skip the refresh if focus just returned from a native OS file
      // picker — otherwise this can wipe out a file the user just picked
      // before the upload's onChange handler gets to read it.
      // See src/lib/file-picker-guard.ts.
      if (isFilePickerCooldownActive()) {
        return;
      }
      void refresh();
    };

    const onVisibilityChange = () => {
      refreshIfVisible();
    };

    window.addEventListener(
      "focus",
      onFocus
    );

    document.addEventListener(
      "visibilitychange",
      onVisibilityChange
    );

    return () => {
      clearInterval(interval);

      window.removeEventListener(
        "focus",
        onFocus
      );

      document.removeEventListener(
        "visibilitychange",
        onVisibilityChange
      );
    };
  }, [
    isStaffSession,
    refresh,
  ]);

  // ─── Staff ────────────────────────────────────────────────────────────────

  const addStaff = useCallback(
    async (
      data: Parameters<
        AppActions["addStaff"]
      >[0]
    ) => {
      const result =
        await apiFetch<{
          temporaryPassword?: string;
        }>("/api/staff", {
          method: "POST",
          body: JSON.stringify({
            ...data,
            role: data.role.toUpperCase(),
          }),
        });

      await refresh();

      return result;
    },
    [refresh]
  );

  const updateStaff = useCallback(
    async (
      id: string,
      patch: Parameters<
        AppActions["updateStaff"]
      >[1]
    ) => {
      const result =
        await apiFetch<{
          temporaryPassword?: string;
        }>(`/api/staff/${id}`, {
          method: "PATCH",
          body: JSON.stringify(patch),
        });

      await refresh();

      return result;
    },
    [refresh]
  );

  const removeStaff = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/staff/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Clients ──────────────────────────────────────────────────────────────

  const addClient = useCallback(
    async (
      data: Parameters<
        AppActions["addClient"]
      >[0]
    ) => {
      await apiFetch(
        "/api/clients",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateClient = useCallback(
    async (
      id: string,
      patch: Partial<Client>
    ) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const removeClient = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Projects ─────────────────────────────────────────────────────────────

  const addProject = useCallback(
    async (
      data: Parameters<
        AppActions["addProject"]
      >[0]
    ) => {
      await apiFetch(
        "/api/projects",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            priority:
              data.priority.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateProject = useCallback(
    async (
      id: string,
      patch: Partial<Project>
    ) => {
      await apiFetch(
        `/api/projects/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const removeProject = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/projects/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  const reassignProject =
    useCallback(
      async (
        projectId: string,
        toArchitectId: string,
        reason: string
      ) => {
        await apiFetch(
          `/api/projects/${projectId}/reassign`,
          {
            method: "POST",
            body: JSON.stringify({
              toArchitectId,
              reason,
            }),
          }
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Daily Logs ───────────────────────────────────────────────────────────

  const addLog = useCallback(
    async (
      data: Parameters<
        AppActions["addLog"]
      >[0]
    ) => {
      const created = await apiFetch<{ id: string }>(
        "/api/logs",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();

      return created;
    },
    [refresh]
  );

  // ─── Comments ─────────────────────────────────────────────────────────────

  const addComment = useCallback(
    async (
      data: Parameters<
        AppActions["addComment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/comments",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            type:
              data.type.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const resolveComment = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/comments/${id}/resolve`,
        {
          method: "POST",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Payments ─────────────────────────────────────────────────────────────

  const addPayment = useCallback(
    async (
      data: Parameters<
        AppActions["addPayment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/payments",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Notifications ───────────────────────────────────────────────────────

  const markNotificationRead =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/notifications/${id}`,
          {
            method: "PATCH",
          }
        );

        setState((s) => ({
          ...s,
          notifications:
            s.notifications.map(
              (notification) =>
                notification.id === id
                  ? {
                      ...notification,
                      read: true,
                    }
                  : notification
            ),
        }));
      },
      []
    );

  // ─── Document Upload ──────────────────────────────────────────────────────

  const uploadDocument =
    useCallback(
      async (
        projectId: string,
        file: File,
        category = "OTHER"
      ): Promise<void> => {
        if (!projectId) {
          throw new Error(
            "A project must be selected before uploading."
          );
        }

        if (!(file instanceof File)) {
          throw new Error(
            "Invalid file selected."
          );
        }

        if (file.size === 0) {
          throw new Error(
            `"${file.name}" is empty.`
          );
        }

        console.log(
          "Starting document upload:",
          {
            projectId,
            fileName: file.name,
            fileSize: file.size,
            mimeType: file.type,
            category,
          }
        );

        const formData =
          new FormData();

        formData.append(
          "file",
          file,
          file.name
        );

        formData.append(
          "projectId",
          projectId
        );

        formData.append(
          "category",
          category
        );

        let response: Response;

        try {
          response = await fetch(
            "/api/documents",
            {
              method: "POST",
              body: formData,
              credentials:
                "same-origin",
              cache: "no-store",
            }
          );
        } catch (error) {
          console.error(
            "Document upload network error:",
            error
          );

          throw new Error(
            "Could not connect to the document upload service."
          );
        }

        const contentType =
          response.headers.get(
            "content-type"
          ) || "";

        let result: unknown = null;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          result = await response
            .json()
            .catch(() => null);
        } else {
          const text =
            await response
              .text()
              .catch(() => "");

          result = {
            error:
              text ||
              `Upload failed with HTTP ${response.status}`,
          };
        }

        console.log(
          "Document upload response:",
          {
            status: response.status,
            result,
          }
        );

        if (!response.ok) {
          if (
            response.status === 401
          ) {
            throw new Error(
              "Your session has expired. Please log in again."
            );
          }

          if (
            response.status === 403
          ) {
            throw new Error(
              "You do not have permission to upload documents to this project."
            );
          }

          if (
            response.status === 413
          ) {
            throw new Error(
              "The file is too large to upload."
            );
          }

          let message =
            `Upload failed with HTTP ${response.status}`;

          if (
            typeof result ===
              "object" &&
            result !== null
          ) {
            const body =
              result as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }

          throw new Error(message);
        }

        if (
          typeof result !==
            "object" ||
          result === null ||
          !("id" in result)
        ) {
          console.error(
            "Upload response did not contain a document ID:",
            result
          );

          throw new Error(
            "The server accepted the upload but did not return a document record."
          );
        }

        console.log(
          "Document uploaded successfully:",
          result
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Documents ────────────────────────────────────────────────────────────

  const removeDocument =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/documents/${id}`,
          {
            method: "DELETE",
          }
        );

        await refresh();
      },
      [refresh]
    );

  const toggleDocumentVisibility =
    useCallback(
      async (
        id: string,
        clientVisible: boolean
      ) => {
        await apiFetch(
          `/api/documents/${id}`,
          {
            method: "PATCH",
            body: JSON.stringify({
              clientVisible,
            }),
          }
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Avatar ───────────────────────────────────────────────────────────────

  const uploadAvatar = useCallback(
    async (file: File) => {
      if (!(file instanceof File)) {
        throw new Error(
          "Invalid file selected."
        );
      }

      const form =
        new FormData();

      form.append(
        "file",
        file,
        file.name
      );

      const res =
        await fetch(
          "/api/users/me/avatar",
          {
            method: "POST",
            body: form,
            credentials:
              "same-origin",
            cache: "no-store",
          }
        );

      if (!res.ok) {
        const contentType =
          res.headers.get(
            "content-type"
          ) || "";

        let message =
          `Avatar upload failed with HTTP ${res.status}`;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          const err =
            await res
              .json()
              .catch(() => null);

          if (
            err &&
            typeof err ===
              "object"
          ) {
            const body =
              err as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }
        }

        throw new Error(message);
      }

      // Patch local state immediately from the response so the new
      // photo shows up right away, instead of waiting on the full
      // 8-endpoint refresh() round-trip. refresh() below still runs
      // to reconcile everything else, but the photo itself no longer
      // depends on its timing.
      const updated = (await res.json()) as { id: string; avatarUrl: string | null };
      setState((s) => ({
        ...s,
        staff: s.staff.map((member) =>
          member.id === updated.id ? { ...member, avatarUrl: updated.avatarUrl } : member
        ),
      }));

      await refresh();
    },
    [refresh]
  );

  const removeAvatar =
    useCallback(
      async () => {
        await apiFetch(
          "/api/users/me/avatar",
          {
            method: "DELETE",
          }
        );

        const myId = session?.user?.id;
        if (myId) {
          setState((s) => ({
            ...s,
            staff: s.staff.map((member) =>
              member.id === myId ? { ...member, avatarUrl: null } : member
            ),
          }));
        }

        await refresh();
      },
      [refresh, session?.user?.id]
    );

  // ─── Provider ─────────────────────────────────────────────────────────────

  return (
    <Ctx.Provider
      value={{
        ...state,

        refresh,

        addStaff,
        updateStaff,
        removeStaff,

        addClient,
        updateClient,
        removeClient,

        addProject,
        updateProject,
        removeProject,
        reassignProject,

        addLog,

        addComment,
        resolveComment,

        addPayment,

        markNotificationRead,

        uploadDocument,
        removeDocument,
        toggleDocumentVisibility,

        uploadAvatar,
        removeAvatar,
      }}
    >
      {children}
    </Ctx.Provider>
  );
}

