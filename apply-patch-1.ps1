      const validation =
        validateDocumentUpload({
          fileName: file.name,
          mimeType:
            file.type ||
            "application/octet-stream",
          sizeBytes: file.size,
        });

      if (!validation.ok) {
        const message =
          validation.error ||
          "This file cannot be uploaded.";

        updateItem(itemId, {
