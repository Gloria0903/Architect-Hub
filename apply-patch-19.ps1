                      const client = clients.find(
                        (item) =>
                          item.id ===
                          project.clientId
                      );

                      const isSelected =
                        selectedProject ===
                        project.id;

                      return (
                        <tr
                          key={project.id}
                          className={`border-t border-line hover:bg-vellum/40 cursor-pointer transition-colors ${
                            isSelected
                              ? "bg-blueprint-bg/30"
                              : ""
                          }`}
                          onClick={() =>
                            setSelectedProject(
                              isSelected
                                ? null
                                : project.id
                            )
                          }
                        >
                          {/* PROJECT */}

                          <td className="px-4 py-3">
                            <div className="text-ink font-medium">
                              {project.name}
                            </div>

                            <div className="text-muted text-[11px] font-mono">
                              {project.sheetNo} ·{" "}
                              {client?.name ||
                                "No client"}
                            </div>
                          </td>

                          {/* CONTRACT */}

                          <td className="px-4 py-3 text-right font-mono text-[11px]">
                            {formatKsh(
                              contractValue
                            )}
                          </td>

                          {/* INVOICED */}

                          <td className="px-4 py-3 text-right font-mono text-[11px]">
                            {formatKsh(invoiced)}

                            <div className="text-[9px] text-muted mt-0.5">
                              Unbilled:{" "}
                              {formatKsh(
                                uninvoiced
                              )}
                            </div>
                          </td>

                          {/* PAID */}

                          <td className="px-4 py-3 text-right font-mono text-[11px] text-moss">
                            {formatKsh(paid)}

                            <div className="text-[9px] text-muted mt-0.5">
                              {paymentPercentage}% of contract
                            </div>
                          </td>

                          {/* OUTSTANDING */}

                          <td className="px-4 py-3 text-right font-mono text-[11px] text-brick">
                            {formatKsh(
                              outstanding
                            )}

                            <div className="text-[9px] text-muted mt-0.5">
                              {collectionPercentage}% collected
                            </div>
                          </td>

                          {/* PROGRESS */}

                          <td className="px-4 py-3">
                            <div className="w-16 h-1.5 bg-line rounded-full overflow-hidden ml-auto">
                              <div
                                className="h-full bg-moss rounded-full"
                                style={{
                                  width: `${paymentPercentage}%`,
                                }}
                              />
                            </div>

                            <div className="text-[9px] text-muted text-right mt-1">
                              Remaining:{" "}
                              {formatKsh(
                                remainingContract
                              )}
                            </div>
                          </td>
                        </tr>
                      );
                    })
                  )}
                </tbody>
              </table>
            </div>
          </Card>

          {/* PAYMENT HISTORY */}

          <Card className="overflow-hidden">
            <div className="px-4 py-3 border-b border-line flex items-center justify-between">
              <div className="font-medium text-ink text-[12.5px]">
                Payment history
              </div>

              {selectedProject && (
                <button
                  type="button"
                  onClick={() =>
                    setSelectedProject(null)
                  }
                  className="text-[11px] text-muted hover:text-ink"
                >
                  Clear filter
                </button>
              )}
            </div>

            <div className="divide-y divide-line max-h-96 overflow-y-auto">
              {projectPayments.length === 0 ? (
                <div className="p-6 text-center text-muted text-[12.5px]">
                  No payments recorded yet.
                </div>
              ) : (
                projectPayments.map((payment) => {
                  const project =
                    projects.find(
                      (item) =>
                        item.id ===
                        payment.projectId
                    );

                  return (
                    <div
                      key={payment.id}
                      className="px-4 py-3"
                    >
                      <div className="flex items-center justify-between mb-1">
                        <div className="font-mono text-[12px] text-moss font-medium">
                          {formatKsh(
                            payment.amount
                          )}
                        </div>

                        <div className="font-mono text-[11px] text-muted">
                          {payment.date}
                        </div>
                      </div>

                      <div className="text-[11.5px] text-ink">
                        {project?.name ||
                          "Unknown project"}
                      </div>

                      <div className="text-[11px] text-muted mt-0.5">
                        {payment.reference ||
                          "No reference"}{" "}
                        ·{" "}
                        {payment.note ||
                          "No note"}
                      </div>
                    </div>
                  );
                })
              )}
            </div>
          </Card>
        </div>

        {/* ------------------------------------------------------------------ */}
        {/* RECORD PAYMENT MODAL */}
        {/* ------------------------------------------------------------------ */}

        <Modal
          open={open}
          onClose={() => setOpen(false)}
          title="Record payment"
          subtitle="This will update the project's paid balance"
        >
          <form
            onSubmit={handleSubmit}
            className="flex flex-col gap-3.5"
          >
            {/* PROJECT */}

            <Field label="Project" required>
              <Select
                required
                value={form.projectId}
                onChange={(e) =>
                  setForm((current) => ({
                    ...current,
                    projectId:
                      e.target.value,
                  }))
                }
              >
                <option value="">
                  Select project
                </option>

                {projects.map((project) => {
                  const outstanding =
                    getOutstanding(project);

                  const invoiced =
                    getInvoiced(project);

                  const paid =
                    getPaid(project);

                  // Only block genuinely settled projects -- invoiced
                  // AND fully paid off. A project that simply hasn't
                  // been invoiced yet (invoiced === 0) still shows
                  // outstanding === 0 by the math, but that's a project
                  // waiting for its first invoice/advance payment, not
                  // one that's done -- it should stay selectable. This
                  // was disabling nearly every active project before.
                  const isFullySettled =
                    invoiced > 0 && outstanding <= 0;

                  return (
                    <option
                      key={project.id}
                      value={project.id}
                      disabled={
                        isFullySettled
                      }
                    >
                      {project.sheetNo} —{" "}
                      {project.name}{" "}
                      (Outstanding:{" "}
                      {formatKsh(
                        outstanding
                      )}{" "}
                      / Invoiced:{" "}
                      {formatKsh(invoiced)}{" "}
                      / Paid:{" "}
                      {formatKsh(paid)})
                    </option>
                  );
                })}
              </Select>
            </Field>

            {/* AMOUNT + DATE */}

            <FormRow>
              <Field
                label="Amount (KSh)"
                required
              >
                <Input
                  type="number"
                  min="1"
                  step="0.01"
                  required
                  value={form.amount}
                  onChange={(e) =>
                    setForm((current) => ({
                      ...current,
                      amount:
                        e.target.value,
                    }))
                  }
                  placeholder="e.g. 2500000"
                />
              </Field>

              <Field
                label="Payment date"
                required
              >
                <Input
                  type="date"
                  required
                  value={form.date}
                  onChange={(e) =>
                    setForm((current) => ({
                      ...current,
                      date:
                        e.target.value,
                    }))
                  }
                />
              </Field>
            </FormRow>

            {/* REFERENCE */}

            <Field label="Reference number">
              <Input
                value={form.reference}
                onChange={(e) =>
                  setForm((current) => ({
                    ...current,
                    reference:
                      e.target.value,
                  }))
                }
                placeholder="e.g. PAY-A101-003"
              />
            </Field>

            {/* NOTE */}

            <Field label="Note">
              <Textarea
                rows={2}
                value={form.note}
                onChange={(e) =>
                  setForm((current) => ({
                    ...current,
                    note: e.target.value,
                  }))
                }
                placeholder="e.g. Second stage payment..."
              />
            </Field>

            {/* PAYMENT SUMMARY */}

            {form.projectId &&
              (() => {
                const project = projects.find(
                  (item) =>
                    item.id ===
                    form.projectId
                );

                if (!project) {
                  return null;
                }

                const contract =
                  getContractValue(project);

                const invoiced =
                  getInvoiced(project);

                const paid =
                  getPaid(project);

                const outstanding =
                  getOutstanding(project);

                const amount = Number(
                  form.amount || 0
                );

                const remainingAfterPayment =
                  Math.max(
                    outstanding - amount,
                    0
                  );

                return (
                  <div className="rounded-md border border-line bg-vellum/50 p-3 text-[11px]">
                    <div className="font-medium text-ink mb-2">
                      Payment summary
                    </div>

                    <div className="grid grid-cols-2 gap-y-1.5">
                      <div className="text-muted">
                        Contract value
                      </div>

                      <div className="text-right font-mono">
                        {formatKsh(contract)}
                      </div>

                      <div className="text-muted">
                        Total invoiced
                      </div>

                      <div className="text-right font-mono">
                        {formatKsh(invoiced)}
                      </div>

                      <div className="text-muted">
                        Already paid
                      </div>

                      <div className="text-right font-mono text-moss">
                        {formatKsh(paid)}
                      </div>

                      <div className="text-muted">
                        Current outstanding
                      </div>

                      <div className="text-right font-mono text-brick">
                        {formatKsh(
                          outstanding
                        )}
                      </div>

                      {amount > 0 && (
                        <>
                          <div className="text-muted border-t border-line pt-1.5 mt-1.5">
                            This payment
                          </div>

                          <div className="text-right font-mono text-moss border-t border-line pt-1.5 mt-1.5">
                            {formatKsh(amount)}
                          </div>

                          <div className="text-muted">
                            Balance after payment
                          </div>

                          <div className="text-right font-mono font-medium">
                            {formatKsh(
                              remainingAfterPayment
                            )}
                          </div>
                        </>
                      )}
                    </div>

                    {amount > outstanding && (
                      <div className="mt-2 text-brick">
                        Payment exceeds the outstanding
                        invoiced balance.
                      </div>
                    )}
                  </div>
                );
              })()}

            {/* ACTIONS */}

            <div className="flex justify-end gap-2 pt-1 border-t border-line mt-1">
              <button
                type="button"
                onClick={() => setOpen(false)}
                className="px-4 py-2 rounded-md text-[12.5px] border border-line text-muted hover:bg-vellum"
              >
                Cancel
              </button>

              <button
                type="submit"
                disabled={(() => {
                  if (
                    !form.projectId ||
                    !form.amount
                  ) {
                    return true;
                  }

                  const amount = Number(
                    form.amount
                  );

                  if (
                    !Number.isFinite(amount) ||
                    amount <= 0
                  ) {
                    return true;
                  }

                  const project =
                    projects.find(
                      (item) =>
                        item.id ===
                        form.projectId
                    );

                  if (!project) {
                    return true;
                  }

                  return (
                    amount >
                    getOutstanding(project)
                  );
                })()}
                className="px-4 py-2 rounded-md text-[12.5px] bg-moss text-white font-medium hover:opacity-90 disabled:opacity-50 disabled:cursor-not-allowed"
              >
                Record payment
              </button>
            </div>
          </form>
        </Modal>

        {/* RECORD INVOICE MODAL */}

        <Modal
          open={invoiceOpen}
          onClose={() => setInvoiceOpen(false)}
          title="Record invoice"
          subtitle="Raises a bill against the project's remaining contract budget"
        >
          <form
            onSubmit={handleInvoiceSubmit}
            className="flex flex-col gap-3.5"
          >
            {/* PROJECT */}

            <Field label="Project" required>
              <Select
                required
                value={invoiceForm.projectId}
                onChange={(e) =>
                  setInvoiceForm((current) => ({
                    ...current,
                    projectId: e.target.value,
                  }))
                }
              >
                <option value="">
                  Select project
                </option>

                {projects.map((project) => {
                  const remaining =
                    getRemainingToInvoice(project);

                  const contract =
                    getContractValue(project);

                  const invoiced =
                    getInvoiced(project);

                  return (
                    <option
                      key={project.id}
                      value={project.id}
                      disabled={remaining <= 0}
                    >
                      {project.sheetNo} —{" "}
                      {project.name}{" "}
                      (Remaining to invoice:{" "}
                      {formatKsh(remaining)}{" "}
                      / Contract:{" "}
                      {formatKsh(contract)}{" "}
                      / Already invoiced:{" "}
                      {formatKsh(invoiced)})
                    </option>
                  );
                })}
              </Select>
            </Field>

            {/* AMOUNT + DATE */}

            <FormRow>
              <Field
                label="Amount (KSh)"
                required
              >
                <Input
                  type="number"
                  min="1"
                  step="0.01"
                  required
                  value={invoiceForm.amount}
                  onChange={(e) =>
                    setInvoiceForm((current) => ({
                      ...current,
                      amount: e.target.value,
                    }))
                  }
                  placeholder="e.g. 2500000"
                />
              </Field>

              <Field
                label="Invoice date"
                required
              >
                <Input
                  type="date"
                  required
                  value={invoiceForm.date}
                  onChange={(e) =>
                    setInvoiceForm((current) => ({
                      ...current,
                      date: e.target.value,
                    }))
                  }
                />
              </Field>
            </FormRow>

            {/* REFERENCE */}

            <Field label="Invoice number">
              <Input
                value={invoiceForm.reference}
                onChange={(e) =>
                  setInvoiceForm((current) => ({
                    ...current,
                    reference: e.target.value,
                  }))
                }
                placeholder="e.g. INV-A101-002"
              />
            </Field>

            {/* NOTE */}

            <Field label="Note">
              <Textarea
                rows={2}
                value={invoiceForm.note}
                onChange={(e) =>
                  setInvoiceForm((current) => ({
                    ...current,
                    note: e.target.value,
                  }))
                }
                placeholder="e.g. Second stage billing..."
              />
            </Field>

            {/* INVOICE SUMMARY */}

            {invoiceForm.projectId &&
              (() => {
                const project = projects.find(
                  (item) =>
                    item.id === invoiceForm.projectId
                );

                if (!project) {
                  return null;
                }

                const contract =
                  getContractValue(project);

                const invoiced =
                  getInvoiced(project);

                const remaining =
                  getRemainingToInvoice(project);

                const amount = Number(
                  invoiceForm.amount || 0
                );

                const remainingAfterInvoice =
                  Math.max(remaining - amount, 0);

                return (
                  <div className="rounded-md border border-line bg-vellum/50 p-3 text-[11px]">
                    <div className="font-medium text-ink mb-2">
                      Invoice summary
                    </div>

                    <div className="grid grid-cols-2 gap-y-1.5">
                      <div className="text-muted">
                        Contract value
                      </div>

                      <div className="text-right font-mono">
                        {formatKsh(contract)}
                      </div>

                      <div className="text-muted">
                        Already invoiced
                      </div>

                      <div className="text-right font-mono">
                        {formatKsh(invoiced)}
                      </div>

                      <div className="text-muted">
                        Remaining to invoice
                      </div>

                      <div className="text-right font-mono text-blueprint">
                        {formatKsh(remaining)}
                      </div>

                      {amount > 0 && (
                        <>
                          <div className="text-muted border-t border-line pt-1.5 mt-1.5">
                            This invoice
                          </div>

                          <div className="text-right font-mono text-blueprint border-t border-line pt-1.5 mt-1.5">
                            {formatKsh(amount)}
                          </div>

                          <div className="text-muted">
                            Remaining after this invoice
                          </div>

                          <div className="text-right font-mono font-medium">
                            {formatKsh(remainingAfterInvoice)}
                          </div>
                        </>
                      )}
                    </div>

                    {amount > remaining && (
                      <div className="mt-2 text-brick">
                        Invoice exceeds the remaining contract budget.
                      </div>
                    )}
                  </div>
                );
              })()}

            {/* ACTIONS */}

            <div className="flex justify-end gap-2 pt-1 border-t border-line mt-1">
              <button
                type="button"
                onClick={() => setInvoiceOpen(false)}
                className="px-4 py-2 rounded-md text-[12.5px] border border-line text-muted hover:bg-vellum"
              >
                Cancel
              </button>

              <button
                type="submit"
                disabled={(() => {
                  if (!invoiceForm.projectId || !invoiceForm.amount) {
                    return true;
                  }

                  const amount = Number(invoiceForm.amount);

                  if (!Number.isFinite(amount) || amount <= 0) {
                    return true;
                  }

                  const project = projects.find(
                    (item) => item.id === invoiceForm.projectId
                  );

                  if (!project) {
                    return true;
                  }

                  return amount > getRemainingToInvoice(project);
                })()}
                className="px-4 py-2 rounded-md text-[12.5px] bg-blueprint text-white font-medium hover:opacity-90 disabled:opacity-50 disabled:cursor-not-allowed"
              >
                Record invoice
              </button>
            </div>
          </form>
        </Modal>
      </div>
    </AppShell>
  );
}
