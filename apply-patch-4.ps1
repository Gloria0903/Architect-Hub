        AppActions["addLog"]
      >[0]
    ) => {
      const created = await apiFetch<{ id: string }>(
        "/api/logs",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();

      return created;
    },
    [refresh]
  );

  // ─── Comments ─────────────────────────────────────────────────────────────

  const addComment = useCallback(
    async (
      data: Parameters<
        AppActions["addComment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/comments",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            type:
              data.type.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const resolveComment = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/comments/${id}/resolve`,
        {
          method: "POST",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Payments ─────────────────────────────────────────────────────────────

  const addPayment = useCallback(
    async (
      data: Parameters<
        AppActions["addPayment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/payments",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Notifications ───────────────────────────────────────────────────────

  const markNotificationRead =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/notifications/${id}`,
          {
            method: "PATCH",
          }
        );

        setState((s) => ({
          ...s,
          notifications:
            s.notifications.map(
              (notification) =>
                notification.id === id
                  ? {
                      ...notification,
                      read: true,
                    }
                  : notification
            ),
        }));
      },
      []
    );

  // ─── Document Upload ──────────────────────────────────────────────────────

  const uploadDocument =
    useCallback(
      async (
        projectId: string,
        file: File,
        category = "OTHER"
      ): Promise<void> => {
        if (!projectId) {
          throw new Error(
            "A project must be selected before uploading."
          );
        }

        if (!(file instanceof File)) {
          throw new Error(
            "Invalid file selected."
          );
        }

        if (file.size === 0) {
          throw new Error(
            `"${file.name}" is empty.`
          );
        }

        console.log(
          "Starting document upload:",
          {
            projectId,
            fileName: file.name,
            fileSize: file.size,
            mimeType: file.type,
            category,
          }
        );

        const formData =
          new FormData();

        formData.append(
          "file",
          file,
          file.name
        );

        formData.append(
          "projectId",
          projectId
        );

        formData.append(
          "category",
          category
        );

        let response: Response;

        try {
          response = await fetch(
            "/api/documents",
            {
              method: "POST",
              body: formData,
              credentials:
                "same-origin",
              cache: "no-store",
            }
          );
        } catch (error) {
          console.error(
            "Document upload network error:",
            error
          );

          throw new Error(
            "Could not connect to the document upload service."
          );
        }

        const contentType =
          response.headers.get(
            "content-type"
          ) || "";

        let result: unknown = null;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          result = await response
            .json()
            .catch(() => null);
        } else {
          const text =
            await response
              .text()
              .catch(() => "");

          result = {
            error:
              text ||
              `Upload failed with HTTP ${response.status}`,
          };
        }

        console.log(
          "Document upload response:",
          {
            status: response.status,
            result,
          }
        );

        if (!response.ok) {
          if (
            response.status === 401
          ) {
            throw new Error(
              "Your session has expired. Please log in again."
            );
          }

          if (
            response.status === 403
          ) {
            throw new Error(
              "You do not have permission to upload documents to this project."
            );
          }

          if (
            response.status === 413
          ) {
            throw new Error(
              "The file is too large to upload."
            );
          }

          let message =
            `Upload failed with HTTP ${response.status}`;

          if (
            typeof result ===
              "object" &&
            result !== null
          ) {
            const body =
              result as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }

          throw new Error(message);
        }

        if (
          typeof result !==
            "object" ||
          result === null ||
          !("id" in result)
        ) {
          console.error(
            "Upload response did not contain a document ID:",
            result
          );

          throw new Error(
            "The server accepted the upload but did not return a document record."
          );
        }

        console.log(
          "Document uploaded successfully:",
          result
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Documents ────────────────────────────────────────────────────────────

  const removeDocument =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/documents/${id}`,
          {
            method: "DELETE",
          }
        );

        await refresh();
      },
      [refresh]
    );

  const toggleDocumentVisibility =
    useCallback(
      async (
        id: string,
        clientVisible: boolean
      ) => {
        await apiFetch(
          `/api/documents/${id}`,
          {
            method: "PATCH",
            body: JSON.stringify({
              clientVisible,
            }),
          }
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Avatar ───────────────────────────────────────────────────────────────

  const uploadAvatar = useCallback(
    async (file: File) => {
      if (!(file instanceof File)) {
        throw new Error(
          "Invalid file selected."
        );
      }

      const form =
        new FormData();

      form.append(
        "file",
        file,
        file.name
      );

      const res =
        await fetch(
          "/api/users/me/avatar",
          {
            method: "POST",
            body: form,
            credentials:
              "same-origin",
            cache: "no-store",
          }
        );

      if (!res.ok) {
        const contentType =
          res.headers.get(
            "content-type"
          ) || "";

        let message =
          `Avatar upload failed with HTTP ${res.status}`;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          const err =
            await res
              .json()
              .catch(() => null);

          if (
            err &&
            typeof err ===
              "object"
          ) {
            const body =
              err as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }
        }

        throw new Error(message);
      }

      // Patch local state immediately from the response so the new
      // photo shows up right away, instead of waiting on the full
      // 8-endpoint refresh() round-trip. refresh() below still runs
      // to reconcile everything else, but the photo itself no longer
      // depends on its timing.
      const updated = (await res.json()) as { id: string; avatarUrl: string | null };
      setState((s) => ({
        ...s,
        staff: s.staff.map((member) =>
          member.id === updated.id ? { ...member, avatarUrl: updated.avatarUrl } : member
        ),
      }));

      await refresh();
    },
    [refresh]
  );

  const removeAvatar =
    useCallback(
      async () => {
        await apiFetch(
          "/api/users/me/avatar",
          {
            method: "DELETE",
          }
        );

        const myId = session?.user?.id;
        if (myId) {
          setState((s) => ({
            ...s,
            staff: s.staff.map((member) =>
              member.id === myId ? { ...member, avatarUrl: null } : member
            ),
          }));
        }

        await refresh();
      },
      [refresh, session?.user?.id]
    );

  // ─── Provider ─────────────────────────────────────────────────────────────

  return (
    <Ctx.Provider
      value={{
        ...state,

        refresh,

        addStaff,
        updateStaff,
        removeStaff,

        addClient,
        updateClient,
        removeClient,

        addProject,
        updateProject,
        removeProject,
        reassignProject,

        addLog,

        addComment,
        resolveComment,

        addPayment,

        markNotificationRead,

        uploadDocument,
        removeDocument,
        toggleDocumentVisibility,

        uploadAvatar,
        removeAvatar,
      }}
    >
      {children}
    </Ctx.Provider>
  );
}

// ─── Hook ────────────────────────────────────────────────────────────────────

export function useStore() {
  const ctx = useContext(Ctx);

  if (!ctx) {
    throw new Error(
      "useStore must be used within AppProvider"
    );
  }

  return ctx;
}
