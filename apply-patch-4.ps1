    },
    [refresh]
  );

  const removeStaff = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/staff/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Clients ──────────────────────────────────────────────────────────────

  const addClient = useCallback(
    async (
      data: Parameters<
        AppActions["addClient"]
      >[0]
    ) => {
      await apiFetch(
        "/api/clients",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateClient = useCallback(
    async (
      id: string,
      patch: Partial<Client>
    ) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const removeClient = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Projects ─────────────────────────────────────────────────────────────

  const addProject = useCallback(
    async (
      data: Parameters<
        AppActions["addProject"]
      >[0]
    ) => {
      await apiFetch(
        "/api/projects",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            priority:
              data.priority.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateProject = useCallback(
    async (
      id: string,
      patch: Partial<Project>
    ) => {
      await apiFetch(
        `/api/projects/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
