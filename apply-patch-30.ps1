  ROOT CAUSE: the dark-mode border color (--color-line: 44 50 58) was
  only ~29 brightness points above the dark page background (18 21 25)
  -- any button relying purely on its border (no filled background,
  like the filter pills and Refresh/Archived buttons in your
  screenshot) was nearly invisible as a result.

  FIX: brightened --color-line in dark mode to 68 76 87 -- roughly
  doubles the contrast delta against the page background (now ~56
  points). Since this is a CSS variable, the fix applies everywhere
  automatically, same as the rest of the dark mode system -- no
  per-page changes needed.

  Run from the ROOT of your local Architect-Hub repo:
    .\apply-patch-30.ps1
#>

$ErrorActionPreference = "Stop"
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Write-PatchFile($RelativePath, $Content) {
  $dir = Split-Path $RelativePath -Parent
  if ($dir -and -not (Test-Path $dir)) {
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
  }
  $full = Join-Path (Get-Location) $RelativePath
  [System.IO.File]::WriteAllText($full, $Content, $utf8NoBom)
  Write-Host "  wrote $RelativePath"
}

Write-Host "Applying Architect Hub patch 30 (dark mode contrast fix)..." -ForegroundColor Cyan

