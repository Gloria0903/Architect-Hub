// ─── Provider ────────────────────────────────────────────────────────────────

export function AppProvider({
  children,
}: {
  children: ReactNode;
}) {
  const {
    status,
    data: session,
  } = useSession();

  const isStaffSession =
    status === "authenticated" &&
    session?.user?.role !== "CLIENT";

  const [state, setState] =
    useState<AppState>({
      staff: [],
      clients: [],
      projects: [],
      logs: [],
      comments: [],
      payments: [],
      notifications: [],
      documents: [],
      loading: false,
      error: null,
    });

  /*
   * Prevent multiple refresh calls from executing
   * simultaneously. If a call comes in while one is already
   * running, we don't just hand back the in-flight promise as-is —
   * that promise may have been *started* before this caller's own
   * mutation (e.g. an avatar or document upload) finished writing to
   * the server, so its snapshot would be stale by the time it
   * resolves. Instead we mark `refreshQueued` and guarantee a fresh
   * follow-up run starts the moment the current one finishes, so
   * every caller is guaranteed data fetched *after* their own write.
   */
  const refreshInFlight =
    useRef<Promise<void> | null>(null);
  const refreshQueued = useRef(false);

  /*
   * True once the FIRST successful (or failed) load has completed.
   * Used to tell the initial page load (nothing on screen yet, a
   * full-page spinner is the right call) apart from every background
   * refresh after that (the 30s poll, window focus, post-mutation
   * refreshes) -- those should update data silently, never blank the
   * whole app back to a spinner. Before this existed, `loading` was set
   * true on every single refresh call, which made the entire app visibly
   * flash back to a full-page spinner every ~30 seconds (or more often
   * under frequent focus events) -- looked exactly like the page
   * reloading, because visually it was.
   */
  const hasLoadedOnce = useRef(false);

  // ─── Refresh all staff data ───────────────────────────────────────────────

  const refresh = useCallback(async (): Promise<void> => {
    if (!isStaffSession) {
      return;
    }

    if (refreshInFlight.current) {
      refreshQueued.current = true;
      return refreshInFlight.current;
    }

    const runOnce = (): Promise<void> => (async () => {
      try {
        if (!hasLoadedOnce.current) {
          setState((s) => ({
            ...s,
            loading: true,
            error: null,
          }));
        }

        /*
         * Each request is deliberately kept separate inside Promise.all.
         * If one endpoint returns HTTP 500, the improved apiFetch()
         * will now tell us EXACTLY which endpoint failed.
         */
        const [
          staff,
          clients,
          projects,
          logs,
          comments,
          payments,
          notificationResponse,
          documents,
        ] = await Promise.all([
          apiFetch<StaffMember[]>(
            "/api/staff"
          ),

          apiFetch<Client[]>(
            "/api/clients"
          ),

          apiFetch<Project[]>(
            "/api/projects"
          ),

          apiFetch<DailyLog[]>(
            "/api/logs"
          ),

          apiFetch<ClientComment[]>(
            "/api/comments"
          ),

          apiFetch<Payment[]>(
            "/api/payments"
          ),

          apiFetch<{
            notifications: Notification[];
            unreadCount: number;
          }>(
            "/api/notifications"
          ),

          apiFetch<Document[]>(
            "/api/documents"
          ),
        ]);

        const notifications =
          notificationResponse?.notifications ??
          [];

        setState({
          staff: staff ?? [],
          clients: clients ?? [],
          projects: projects ?? [],
          logs: logs ?? [],
          comments: comments ?? [],
          payments: payments ?? [],
          notifications,
          documents: documents ?? [],
          loading: false,
          error: null,
        });

        hasLoadedOnce.current = true;
      } catch (error) {
        console.error(
          "Failed to refresh application data:",
          error
        );

        const message =
          error instanceof Error
            ? error.message
            : "Failed to load application data.";

        if (!hasLoadedOnce.current) {
          // Initial load failed -- there's nothing on screen yet, so
          // showing the blocking error state is the right call, and this
          // also marks the "first load" attempt as resolved either way.
          setState((s) => ({
            ...s,
            loading: false,
            error: message,
          }));
          hasLoadedOnce.current = true;
        } else {
          // A background refresh failed after we already have real data
          // on screen (e.g. a transient network blip during the 30s
          // poll). Don't blank the whole app to an error screen over
          // this -- keep showing the last-known-good data and quietly
          // try again on the next cycle.
          setState((s) => ({
            ...s,
            loading: false,
          }));
        }
      }
    })();

    const promise = runOnce().then(() => {
      // If another caller asked for a refresh while this run was in
      // flight, their write may have landed after our fetch started —
      // run once more immediately so they get a fresh snapshot instead
      // of silently keeping whatever we just fetched.
      if (refreshQueued.current) {
        refreshQueued.current = false;
        refreshInFlight.current = runOnce().finally(() => {
          refreshInFlight.current = null;
        });
        return refreshInFlight.current;
      }
      refreshInFlight.current = null;
    });

    refreshInFlight.current = promise;

    return promise;
  }, [isStaffSession]);

  // ─── Initial data load ────────────────────────────────────────────────────

  useEffect(() => {
  if (status === "loading") {
    return;
  }

  if (isStaffSession) {
    void refresh();
  }
}, [status, isStaffSession, refresh]);

  // ─── Keep data fresh ──────────────────────────────────────────────────────

  useEffect(() => {
    if (!isStaffSession) {
      return;
    }

    // Passive refresh triggers (the 30s poll, window focus) are throttled
    // to at most once per 10s combined, no matter how many of either
    // fire -- window focus in particular can fire far more often than
    // once per 30s (alt-tabbing, notifications stealing focus, a second
    // monitor). This is purely about the BACKGROUND refresh triggers;
    // action-triggered refreshes (after submitting a log, adding a
    // client, etc.) always call refresh() directly and are never
    // throttled, so the person who just did something still sees it
    // immediately.
    const MIN_PASSIVE_REFRESH_GAP_MS = 10_000;
    let lastPassiveRefreshAt = 0;

    const passiveRefresh = () => {
      const now = Date.now();
      if (now - lastPassiveRefreshAt < MIN_PASSIVE_REFRESH_GAP_MS) {
        return;
      }
      lastPassiveRefreshAt = now;
      void refresh();
    };

    const refreshIfVisible = () => {
      if (
        document.visibilityState ===
          "visible" &&
        !isFilePickerOpen()
      ) {
        passiveRefresh();
      }
    };

    const interval = setInterval(
      refreshIfVisible,
      30000
    );

    const onFocus = () => {
      // If a native file picker was open, this focus event is the dialog
      // closing -- skip exactly this one refresh so React's onChange for
      // the file input gets a chance to run first. See
      // src/lib/file-picker-guard.ts.
      if (consumeFilePickerReturn()) {
        return;
      }
      passiveRefresh();
    };

    const onVisibilityChange = () => {
      refreshIfVisible();
    };

    window.addEventListener(
      "focus",
      onFocus
    );

    document.addEventListener(
      "visibilitychange",
      onVisibilityChange
    );

    return () => {
      clearInterval(interval);

      window.removeEventListener(
        "focus",
        onFocus
      );

      document.removeEventListener(
        "visibilitychange",
        onVisibilityChange
      );
    };
  }, [
    isStaffSession,
    refresh,
  ]);

  // ─── Staff ────────────────────────────────────────────────────────────────

  const addStaff = useCallback(
    async (
      data: Parameters<
        AppActions["addStaff"]
      >[0]
    ) => {
      const result =
        await apiFetch<{
          temporaryPassword?: string;
          invited?: boolean;
        }>("/api/staff", {
          method: "POST",
          body: JSON.stringify({
            ...data,
            role: data.role.toUpperCase(),
          }),
        });

      await refresh();

      return result;
    },
    [refresh]
  );

  const updateStaff = useCallback(
    async (
      id: string,
      patch: Parameters<
        AppActions["updateStaff"]
      >[1]
    ) => {
      const result =
        await apiFetch<{
          temporaryPassword?: string;
        }>(`/api/staff/${id}`, {
          method: "PATCH",
          body: JSON.stringify(patch),
        });

      await refresh();

      return result;
    },
    [refresh]
  );

  const removeStaff = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/staff/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Clients ──────────────────────────────────────────────────────────────

  const addClient = useCallback(
    async (
      data: Parameters<
        AppActions["addClient"]
      >[0]
    ) => {
      await apiFetch(
        "/api/clients",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateClient = useCallback(
    async (
      id: string,
      patch: Partial<Client>
    ) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const removeClient = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/clients/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Projects ─────────────────────────────────────────────────────────────

  const addProject = useCallback(
    async (
      data: Parameters<
        AppActions["addProject"]
      >[0]
    ) => {
      await apiFetch(
        "/api/projects",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            priority:
              data.priority.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const updateProject = useCallback(
    async (
      id: string,
      patch: Partial<Project>
    ) => {
      await apiFetch(
        `/api/projects/${id}`,
        {
          method: "PATCH",
          body: JSON.stringify(patch),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const removeProject = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/projects/${id}`,
        {
          method: "DELETE",
        }
      );

      await refresh();
    },
    [refresh]
  );

  const reassignProject =
    useCallback(
      async (
        projectId: string,
        toArchitectId: string,
        reason: string
      ) => {
        await apiFetch(
          `/api/projects/${projectId}/reassign`,
          {
            method: "POST",
            body: JSON.stringify({
              toArchitectId,
              reason,
            }),
          }
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Daily Logs ───────────────────────────────────────────────────────────

  const addLog = useCallback(
    async (
      data: Parameters<
        AppActions["addLog"]
      >[0]
    ) => {
      const created = await apiFetch<{ id: string }>(
        "/api/logs",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();

      return created;
    },
    [refresh]
  );

  // ─── Comments ─────────────────────────────────────────────────────────────

  const addComment = useCallback(
    async (
      data: Parameters<
        AppActions["addComment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/comments",
        {
          method: "POST",
          body: JSON.stringify({
            ...data,
            type:
              data.type.toUpperCase(),
          }),
        }
      );

      await refresh();
    },
    [refresh]
  );

  const resolveComment = useCallback(
    async (id: string) => {
      await apiFetch(
        `/api/comments/${id}/resolve`,
        {
          method: "POST",
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Payments ─────────────────────────────────────────────────────────────

  const addPayment = useCallback(
    async (
      data: Parameters<
        AppActions["addPayment"]
      >[0]
    ) => {
      await apiFetch(
        "/api/payments",
        {
          method: "POST",
          body: JSON.stringify(data),
        }
      );

      await refresh();
    },
    [refresh]
  );

  // ─── Notifications ───────────────────────────────────────────────────────

  const markNotificationRead =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/notifications/${id}`,
          {
            method: "PATCH",
          }
        );

        setState((s) => ({
          ...s,
          notifications:
            s.notifications.map(
              (notification) =>
                notification.id === id
                  ? {
                      ...notification,
                      read: true,
                    }
                  : notification
            ),
        }));
      },
      []
    );

  // ─── Document Upload ──────────────────────────────────────────────────────

  const uploadDocument =
    useCallback(
      async (
        projectId: string,
        file: File,
        category = "OTHER"
      ): Promise<void> => {
        if (!projectId) {
          throw new Error(
            "A project must be selected before uploading."
          );
        }

        if (!(file instanceof File)) {
          throw new Error(
            "Invalid file selected."
          );
        }

        if (file.size === 0) {
          throw new Error(
            `"${file.name}" is empty.`
          );
        }

        console.log(
          "Starting document upload:",
          {
            projectId,
            fileName: file.name,
            fileSize: file.size,
            mimeType: file.type,
            category,
          }
        );

        const formData =
          new FormData();

        formData.append(
          "file",
          file,
          file.name
        );

        formData.append(
          "projectId",
          projectId
        );

        formData.append(
          "category",
          category
        );

        let response: Response;

        try {
          response = await fetch(
            "/api/documents",
            {
              method: "POST",
              body: formData,
              credentials:
                "same-origin",
              cache: "no-store",
            }
          );
        } catch (error) {
          console.error(
            "Document upload network error:",
            error
          );

          throw new Error(
            "Could not connect to the document upload service."
          );
        }

        const contentType =
          response.headers.get(
            "content-type"
          ) || "";

        let result: unknown = null;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          result = await response
            .json()
            .catch(() => null);
        } else {
          const text =
            await response
              .text()
              .catch(() => "");

          result = {
            error:
              text ||
              `Upload failed with HTTP ${response.status}`,
          };
        }

        console.log(
          "Document upload response:",
          {
            status: response.status,
            result,
          }
        );

        if (!response.ok) {
          if (
            response.status === 401
          ) {
            throw new Error(
              "Your session has expired. Please log in again."
            );
          }

          if (
            response.status === 403
          ) {
            throw new Error(
              "You do not have permission to upload documents to this project."
            );
          }

          if (
            response.status === 413
          ) {
            throw new Error(
              "The file is too large to upload."
            );
          }

          let message =
            `Upload failed with HTTP ${response.status}`;

          if (
            typeof result ===
              "object" &&
            result !== null
          ) {
            const body =
              result as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }

          throw new Error(message);
        }

        if (
          typeof result !==
            "object" ||
          result === null ||
          !("id" in result)
        ) {
          console.error(
            "Upload response did not contain a document ID:",
            result
          );

          throw new Error(
            "The server accepted the upload but did not return a document record."
          );
        }

        console.log(
          "Document uploaded successfully:",
          result
        );

        await refresh();
      },
      [refresh]
    );

  // ─── Documents ────────────────────────────────────────────────────────────

  const removeDocument =
    useCallback(
      async (id: string) => {
        await apiFetch(
          `/api/documents/${id}`,
          {
            method: "DELETE",
          }
        );

        await refresh();
      },
      [refresh]
