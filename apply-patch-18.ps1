        await refresh();
      },
      [refresh]
    );

  // ─── Avatar ───────────────────────────────────────────────────────────────

  const uploadAvatar = useCallback(
    async (file: File) => {
      if (!(file instanceof File)) {
        throw new Error(
          "Invalid file selected."
        );
      }

      const form =
        new FormData();

      form.append(
        "file",
        file,
        file.name
      );

      const res =
        await fetch(
          "/api/users/me/avatar",
          {
            method: "POST",
            body: form,
            credentials:
              "same-origin",
            cache: "no-store",
          }
        );

      if (!res.ok) {
        const contentType =
          res.headers.get(
            "content-type"
          ) || "";

        let message =
          `Avatar upload failed with HTTP ${res.status}`;

        if (
          contentType.includes(
            "application/json"
          )
        ) {
          const err =
            await res
              .json()
              .catch(() => null);

          if (
            err &&
            typeof err ===
              "object"
          ) {
            const body =
              err as Record<
                string,
                unknown
              >;

            if (
              typeof body.error ===
              "string"
            ) {
              message =
                body.error;
            } else if (
              typeof body.message ===
              "string"
            ) {
              message =
                body.message;
            }
          }
        }

        throw new Error(message);
      }

      // Patch local state immediately from the response so the new
      // photo shows up right away, instead of waiting on the full
      // 8-endpoint refresh() round-trip. refresh() below still runs
      // to reconcile everything else, but the photo itself no longer
      // depends on its timing.
      const updated = (await res.json()) as { id: string; avatarUrl: string | null };
      setState((s) => ({
        ...s,
        staff: s.staff.map((member) =>
          member.id === updated.id ? { ...member, avatarUrl: updated.avatarUrl } : member
        ),
      }));

      await refresh();
    },
    [refresh]
  );

  const removeAvatar =
    useCallback(
      async () => {
        await apiFetch(
          "/api/users/me/avatar",
          {
            method: "DELETE",
          }
        );

        const myId = session?.user?.id;
        if (myId) {
          setState((s) => ({
            ...s,
            staff: s.staff.map((member) =>
              member.id === myId ? { ...member, avatarUrl: null } : member
            ),
          }));
        }

        await refresh();
      },
      [refresh, session?.user?.id]
    );

  // ─── Provider ─────────────────────────────────────────────────────────────

  return (
    <Ctx.Provider
      value={{
        ...state,

        refresh,

        addStaff,
        updateStaff,
        removeStaff,

        addClient,
        updateClient,
        removeClient,

        addProject,
        updateProject,
        removeProject,
        reassignProject,

        addLog,

        addComment,
        resolveComment,

