   */

  async function handleSubmit(
    e: React.FormEvent<HTMLFormElement>
  ) {
    e.preventDefault();

    const amount = Number(form.amount);

    if (
      !form.projectId ||
      !Number.isFinite(amount) ||
      amount <= 0
    ) {
      return;
    }

    const project = projects.find(
      (item) => item.id === form.projectId
    );

    if (!project) {
      alert(
        "The selected project could not be found."
      );
      return;
    }

    /*
     * Payments are limited to the amount that has actually
     * been invoiced and remains unpaid.
     */
    const outstanding = getOutstanding(project);

    if (outstanding <= 0) {
      alert(
        "This project has no outstanding invoiced balance."
      );
      return;
    }

    if (amount > outstanding) {
      alert(
        `Payment cannot exceed the outstanding invoiced balance of ${formatKsh(
          outstanding
        )}.`
      );
      return;
    }

    try {
      await addPayment({
        projectId: form.projectId,
        amount,
        date: form.date,
        reference: form.reference.trim(),
        note: form.note.trim(),
      });

      setOpen(false);

      setForm({
        projectId: "",
        amount: "",
        date: "",
        reference: "",
        note: "",
      });
    } catch (error) {
      console.error(
        "Failed to record payment:",
        error
      );

      alert(
        error instanceof Error
          ? error.message
          : "Failed to record payment."
      );
    }
  }

  /*
   * --------------------------------------------------------------------------
   * PAYMENT HISTORY
   * --------------------------------------------------------------------------
   */

