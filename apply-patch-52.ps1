   * ---------------------------------------------------------
   * Perform reassignment atomically
   * ---------------------------------------------------------
   *
   * Both operations must succeed:
   *
   * 1. Change project architect
   * 2. Create assignment history
   *
   * If either fails, the transaction rolls back.
   */

