   * ---------------------------------------------------------
   * Notify new architect
   * ---------------------------------------------------------
   *
   * Notification failure must not undo the successful
   * reassignment.
   */

  try {
    await notifyProjectAssignment({
      userId: toArchitectId,

      projectId: id,

      projectName:
        `${project.name} (${project.sheetNo})`,

      assignedRole: "ARCHITECT",

      assignedByName:
        session.user.name ??
        "An administrator",
    });
  } catch (error) {
    console.error(
      "Project reassignment notification failed:",
      error
    );
  }

  /*
   * Same flat-fetch pattern used elsewhere in this app: matches what
   * the removed nested client/architect/supervisor select used to
   * provide, without the join that fails on this host.
   */
  const [reassignClient, reassignArchitect, reassignSupervisor] = await Promise.all([
