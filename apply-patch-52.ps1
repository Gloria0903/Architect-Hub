   * ---------------------------------------------------------
   * Load project
   * ---------------------------------------------------------
   */

  const project = await prisma.project.findUnique({
    where: {
      id,
    },

    select: {
      id: true,
      name: true,
      sheetNo: true,
      architectId: true,
      archivedAt: true,
    },
  });

