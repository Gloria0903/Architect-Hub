// ─── API Helper ──────────────────────────────────────────────────────────────

async function apiFetch<T>(
  url: string,
  options: RequestInit = {}
): Promise<T> {
  const method = options.method ?? "GET";

  const headers = new Headers(options.headers);

  /*
   * Only add Content-Type for requests that actually send JSON.
   * This is important because FormData uploads must NOT have
   * Content-Type manually set.
   */
  if (
    options.body &&
    !(options.body instanceof FormData) &&
    !headers.has("Content-Type")
  ) {
    headers.set("Content-Type", "application/json");
  }

  try {
    const res = await fetch(url, {
      ...options,
      method,
      headers,
      credentials: "same-origin",
      cache: "no-store",
    });

    const contentType =
      res.headers.get("content-type") || "";

    const isJson =
      contentType.includes("application/json");

    let responseBody: unknown = null;

    if (isJson) {
      responseBody = await res
        .json()
        .catch(() => null);
    } else {
      responseBody = await res
        .text()
        .catch(() => "");
    }

    if (!res.ok) {
      console.error(
        `[API ${res.status}] ${method} ${url}`,
        responseBody
      );

      if (res.status === 401) {
        throw new Error(
          `Unauthorized: your session may have expired.`
        );
      }

      if (res.status === 403) {
        throw new Error(
          `Forbidden: you do not have permission to perform this action.`
        );
      }

      if (res.status === 404) {
        throw new Error(
          `API endpoint not found: ${method} ${url}`
        );
      }

      if (res.status === 413) {
        throw new Error(
          `The uploaded file is too large.`
        );
      }

      let serverMessage = "";

      if (
        typeof responseBody === "object" &&
        responseBody !== null
      ) {
        const body = responseBody as Record<
          string,
          unknown
        >;

        if (typeof body.error === "string") {
          serverMessage = body.error;
        } else if (
          typeof body.error === "object" &&
          body.error !== null
        ) {
          /*
           * Many routes return Zod's parsed.error.flatten() directly
           * as `error` on a 400 -- an object shaped like
           * { formErrors: string[], fieldErrors: { [field]: string[] } },
           * not a plain string. Without this, that whole object was
           * silently dropped and the person just saw a generic
           * "API request failed" message with zero indication of what
           * was actually wrong (e.g. "location must be at least 2
           * characters" -- a real, specific, fixable reason).
           */
          const zodShape = body.error as {
            fieldErrors?: Record<string, string[]>;
            formErrors?: string[];
          };

          const fieldMessages = zodShape.fieldErrors
            ? Object.entries(zodShape.fieldErrors)
                .filter(([, msgs]) => Array.isArray(msgs) && msgs.length > 0)
                .map(([field, msgs]) => `${field}: ${msgs.join(", ")}`)
            : [];

          const formMessages = Array.isArray(zodShape.formErrors)
            ? zodShape.formErrors
            : [];

          serverMessage = [...fieldMessages, ...formMessages].join("; ");
        } else if (
          typeof body.message === "string"
        ) {
          serverMessage = body.message;
        }
      } else if (
        typeof responseBody === "string"
      ) {
        serverMessage = responseBody;
      }

      throw new Error(
        serverMessage ||
          `API request failed: ${method} ${url} (HTTP ${res.status})`
      );
    }

    if (!isJson) {
      throw new Error(
        `Server returned a non-JSON response for ${method} ${url}.`
      );
    }

    return responseBody as T;
  } catch (error) {
    if (error instanceof Error) {
      console.error(
        `API request failed: ${method} ${url}`,
        error
      );

      throw error;
    }

    throw new Error(
      `API request failed: ${method} ${url}`
    );
  }
}

