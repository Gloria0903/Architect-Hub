          subtitle="This will update the project's paid balance"
        >
          <form
            onSubmit={handleSubmit}
            className="flex flex-col gap-3.5"
          >
            {/* PROJECT */}

            <Field label="Project" required>
              <Select
                required
                value={form.projectId}
                onChange={(e) =>
                  setForm((current) => ({
                    ...current,
                    projectId:
                      e.target.value,
                  }))
                }
              >
                <option value="">
                  Select project
                </option>

