            </div>
          </Card>
        </div>

        {/* ------------------------------------------------------------------ */}
        {/* RECORD PAYMENT MODAL */}
        {/* ------------------------------------------------------------------ */}

        <Modal
          open={open}
          onClose={() => setOpen(false)}
