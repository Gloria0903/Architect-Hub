                      key={project.id}
                      value={project.id}
                      disabled={
                        isFullySettled
                      }
                    >
                      {project.sheetNo} —{" "}
                      {project.name}{" "}
                      (Remaining:{" "}
                      {formatKsh(
                        remaining
                      )}{" "}
                      / Contract:{" "}
                      {formatKsh(budget)}{" "}
                      / Paid:{" "}
                      {formatKsh(paid)})
                    </option>
                  );
                })}
              </Select>
            </Field>

            {/* AMOUNT + DATE */}

            <FormRow>
              <Field
                label="Amount (KSh)"
                required
              >
                <Input
                  type="number"
                  min="1"
                  step="0.01"
                  required
                  value={form.amount}
                  onChange={(e) =>
                    setForm((current) => ({
                      ...current,
                      amount:
                        e.target.value,
                    }))
                  }
                  placeholder="e.g. 2500000"
                />
              </Field>

              <Field
                label="Payment date"
                required
              >
                <Input
                  type="date"
                  required
                  value={form.date}
                  onChange={(e) =>
                    setForm((current) => ({
                      ...current,
                      date:
                        e.target.value,
                    }))
                  }
                />
              </Field>
            </FormRow>

            {/* REFERENCE */}

            <Field label="Reference number">
              <Input
                value={form.reference}
                onChange={(e) =>
                  setForm((current) => ({
                    ...current,
                    reference:
                      e.target.value,
                  }))
                }
                placeholder="e.g. PAY-A101-003"
              />
            </Field>

