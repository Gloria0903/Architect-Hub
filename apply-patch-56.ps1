          <Card className="overflow-hidden">
            <div className="px-4 py-3 border-b border-line flex items-center justify-between">
              <div className="font-medium text-ink text-[12.5px]">
                Payment history
              </div>

              {selectedProject && (
                <button
                  type="button"
                  onClick={() =>
                    setSelectedProject(null)
                  }
                  className="text-[11px] text-muted hover:text-ink"
                >
                  Clear filter
                </button>
              )}
            </div>

            <div className="divide-y divide-line max-h-96 overflow-y-auto">
              {projectPayments.length === 0 ? (
                <div className="p-6 text-center text-muted text-[12.5px]">
                  No payments recorded yet.
                </div>
              ) : (
                projectPayments.map((payment) => {
                  const project =
                    projects.find(
                      (item) =>
                        item.id ===
                        payment.projectId
                    );

                  return (
                    <div
                      key={payment.id}
                      className="px-4 py-3"
                    >
                      <div className="flex items-center justify-between mb-1">
                        <div className="font-mono text-[12px] text-moss font-medium">
                          {formatKsh(
                            payment.amount
                          )}
                        </div>

                        <div className="font-mono text-[11px] text-muted">
                          {payment.date}
                        </div>
                      </div>

                      <div className="text-[11.5px] text-ink">
                        {project?.name ||
                          "Unknown project"}
                      </div>

                      <div className="text-[11px] text-muted mt-0.5">
                        {payment.reference ||
                          "No reference"}{" "}
                        ·{" "}
                        {payment.note ||
                          "No note"}
                      </div>
                    </div>
                  );
                })
              )}
            </div>
          </Card>

          {/* INVOICE HISTORY */}

          <Card className="overflow-hidden">
            <div className="px-4 py-3 border-b border-line flex items-center justify-between">
              <div className="font-medium text-ink text-[12.5px]">
                Invoice history
              </div>

              {selectedProject && (
                <button
                  type="button"
                  onClick={() =>
                    setSelectedProject(null)
                  }
                  className="text-[11px] text-muted hover:text-ink"
                >
                  Clear filter
                </button>
              )}
            </div>

            <div className="divide-y divide-line max-h-96 overflow-y-auto">
              {projectInvoices.length === 0 ? (
                <div className="p-6 text-center text-muted text-[12.5px]">
                  No invoices recorded yet.
                </div>
              ) : (
                projectInvoices.map((invoice) => {
                  const project =
                    projects.find(
                      (item) =>
                        item.id ===
                        invoice.projectId
                    );

                  return (
                    <Link
                      key={invoice.id}
                      href={`/finance/invoices/${invoice.id}`}
                      className="block px-4 py-3 hover:bg-vellum/60 transition-colors"
                    >
                      <div className="flex items-center justify-between mb-1">
                        <div className="font-mono text-[12px] text-blueprint font-medium">
                          {formatKsh(
                            invoice.amount
                          )}
                        </div>

                        <div className="font-mono text-[11px] text-muted">
                          {invoice.date}
                        </div>
                      </div>

                      <div className="text-[11.5px] text-ink">
                        {project?.name ||
                          "Unknown project"}
                      </div>

                      <div className="text-[11px] text-muted mt-0.5">
                        {invoice.reference ||
                          "No reference"}{" "}
                        ·{" "}
                        {invoice.note ||
                          "No note"}
                        {" · "}
                        <span className="text-blueprint">View / print</span>
                      </div>
                    </Link>
