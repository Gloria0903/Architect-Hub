  ROOT CAUSE: every .ps1 patch script I sent before this one had no BOM
  of its own. Windows PowerShell (5.1, the built-in one -- not
  PowerShell 7) reads a script file with no BOM using the system's
  legacy code page instead of UTF-8. Any literal em-dash, arrow, or
  curly quote embedded in the script text -- which was in almost every
  file I sent, mostly in comments and in a few UI strings like "Manage ->"
  links -- got silently corrupted the moment your machine READ the
  script, before it ever wrote a single file. That's the "a,!,,a...""
  garbage you saw on the dashboard.

  THIS script fixes it two ways:
   1. This .ps1 file itself now has a UTF-8 BOM, so PowerShell reads
      it correctly this time.
   2. It rewrites EVERY file this session has touched or created, all
      34 of them, from clean source -- not just the ones with a visibly
      broken character, since corruption could be silent elsewhere too.

  The files it WRITES still get no BOM (same as always -- Prisma's
  schema parser breaks on a BOM in that direction, unrelated issue from
  early in this session).

  Run from the ROOT of your local Architect-Hub repo:
    .\apply-patch-10.ps1
#>

$ErrorActionPreference = "Stop"
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function Write-PatchFile($RelativePath, $Content) {
  $dir = Split-Path $RelativePath -Parent
  if ($dir -and -not (Test-Path $dir)) {
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
  }
  $full = Join-Path (Get-Location) $RelativePath
  [System.IO.File]::WriteAllText($full, $Content, $utf8NoBom)
  Write-Host "  wrote $RelativePath"
}

